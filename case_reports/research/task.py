"""The application's generic scientific objective, separate from developer tasks."""

RESEARCH_OBJECTIVE = """Discover and assess examples of pragmatic causal pluralism in natural
phenomena: where a presently available causal representation fails to transfer usefully
between explanatory tasks, and why it fails. Establish the failure of a specified
representation or attempted repair under stated conditions, not fundamental incompatibility
or the impossibility of every future reduction. Ground examples in research about the
natural phenomena and their explanatory theories, not just the operation of a calculator.
Explore candidate generalized causal inferences G and identify which meaningful predictions
or explanations in hypotheses or theories depend on each inference. A mechanism's existence
and the usefulness of a particular representation of its causal contribution are different claims.
The tasks can differ in questions, quantities, organisms, scales, grain or framing. Establish
their connection through G and explain the mapping; do not require identical settings or
opposite signs on an identical observable as an entry condition. Preserve each task's native
quantities and success criteria; any numerical comparison still needs a justified mapping.
Propose expected generalizability bounds grounded in literature or reasoning across literature
where possible; explicitly provisional judgment is permitted when that grounding is
unavailable. Their purpose is to expose and explain broken expectations, not establish
absolutely correct bounds. Revise them as more hypotheses are investigated, recording
what was expected, what challenged it, and why a revision expands or restricts the bounds
or changes G. Distinguish repairs through better definitions or a missing dependency
within a general rule set from magic fudge factors or special rules outside that set.
Additional contexts of essentially the same theory supply further evidence. Distinguish
them from a different theory that meaningfully depends on G. Investigate consequential
failures arising from conceptualization, grain, framing or approximation: carrying G over
unchanged may worsen a prediction or require assumptions or information that defeat the
destination task. Omitting, aggregating or reformulating G may restore usefulness without
making the original mechanism nonexistent. Neither more detail nor less detail is inherently better.
Identify the actual attempted transfer, evidence of failure, and the explanation for that
failure; distinguish demonstrated causes from proposed explanations and missing evidence.
You may construct and evaluate a transfer through public derivation from sourced premises
across literature; no single paper must already identify the failure. Distinguish published
outcomes from newly derived conditional consequences. A proposed transfer alone is not a test.
Compare concrete conditioning, added-variable or refinement attempts and retain successful
repairs as findings. Account for retained successes, scope losses, fitting assumptions,
predictive losses and information costs. A fitted reconciliation alone does not establish
usefulness. Separate accommodation of known facts from additional predictions and their
independent corroboration. An explained current failure can be a finding even when no useful
replacement is known. A mere omission, relabeling, new contrary observation or unavailable
source does not establish such a failure. Scope conclusions to the models, evidence and
alternatives examined; retain uncertainty and useful refutations. Select and
revisit promising candidates through the scoring sheets; no particular candidate,
scientific domain, author, paper, or illustrative example is prescribed.
"""

